#!/usr/bin/env python3
"""Render the bootstrapper's icons (ui-icons/*.svg) into ui/icons.h.

The release's GTK has no SVG loader, so each icon is rendered once with
rsvg-convert into a 72 px PNG and embedded in the UI binary. The UI uses
only its alpha channel, as a mask painted in the CSS text colour of the
place it is drawn, so one icon serves every colour.

    python3 make-ui-icons.py           regenerate ui/icons.h (needs rsvg-convert)
    python3 make-ui-icons.py --check   fail when ui/icons.h does not list exactly ui-icons/
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = HERE / "ui-icons"
OUTPUT = HERE / "ui" / "icons.h"
SIZE = 72


def names():
    return sorted(svg.stem for svg in SOURCES.glob("*.svg"))


def generate():
    parts = ["/* Generated by make-ui-icons.py from the SVG files in ui-icons; do not edit. */\n",
             f"#define UI_ICON_SIZE {SIZE}\n"]
    table = []
    for name in names():
        png = subprocess.run(["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE), str(SOURCES / f"{name}.svg")],
                             check=True, capture_output=True).stdout
        ident = "ui_icon_" + re.sub(r"[^a-z0-9]", "_", name)
        rows = [", ".join(str(b) for b in png[i:i + 24]) for i in range(0, len(png), 24)]
        parts.append(f"static const unsigned char {ident}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
        table.append(f'    {{"{name}", {ident}, sizeof {ident}}},')
    parts.append("static const struct { const char *name; const unsigned char *png; unsigned int size; } UI_ICONS[] = {\n"
                 + "\n".join(table) + "\n};\n")
    OUTPUT.write_text("".join(parts))
    print(f"wrote {OUTPUT.relative_to(HERE)}: {len(table)} icons")


def check():
    text = OUTPUT.read_text() if OUTPUT.exists() else ""
    embedded = re.findall(r'\{"([a-z0-9-]+)", ui_icon_', text)
    if embedded != names():
        sys.exit(f"ui/icons.h is stale: has {embedded}, ui-icons has {names()}; run make-ui-icons.py")
    print(f"PASS ui icons: {len(embedded)} embedded")


if __name__ == "__main__":
    check() if sys.argv[1:] == ["--check"] else generate()
